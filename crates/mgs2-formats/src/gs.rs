/// 4 MiB of GS local memory.
pub struct GsMem {
    mem: Vec<u8>,
}

impl Default for GsMem {
    fn default() -> Self {
        Self { mem: vec![0; 4 << 20] }
    }
}

impl GsMem {
    fn word_addr32(bp: u32, bw: u32, x: u32, y: u32) -> usize {
        let page = (y / 32) * bw.max(1) + x / 64;
        let block = bp + page * 32 + BLOCK32[((y % 32) / 8) as usize][((x % 64) / 8) as usize];
        ((block * 64 + COLUMN32[(y % 8) as usize][(x % 8) as usize]) as usize * 4) % (4 << 20)
    }

    /// Host-to-local transfer in PSMCT32 starting at (0,0) of the buffer.
    pub fn upload32(&mut self, bp: u32, bw: u32, width: u32, data: &[u8]) {
        for (i, px) in data.as_chunks::<4>().0.iter().enumerate() {
            let (x, y) = (i as u32 % width, i as u32 / width);
            let a = Self::word_addr32(bp, bw, x, y);
            self.mem[a..a + 4].copy_from_slice(px);
        }
    }

    pub fn read32(&self, bp: u32, bw: u32, x: u32, y: u32) -> [u8; 4] {
        let a = Self::word_addr32(bp, bw, x, y);
        self.mem[a..a + 4].try_into().unwrap()
    }

    pub fn read8(&self, bp: u32, bw: u32, x: u32, y: u32) -> u8 {
        let page = (y / 64) * (bw / 2).max(1) + x / 128;
        let block = bp + page * 32 + BLOCK8[((y % 64) / 16) as usize][((x % 128) / 16) as usize];
        let a = (block * 256 + COLUMN8[(y % 16) as usize][(x % 16) as usize]) as usize;
        self.mem[a % self.mem.len()]
    }

    pub fn read4(&self, bp: u32, bw: u32, x: u32, y: u32) -> u8 {
        let page = (y / 128) * (bw / 2).max(1) + x / 128;
        let block = bp + page * 32 + BLOCK4[((y % 128) / 16) as usize][((x % 128) / 32) as usize];
        let nib = (block * 512 + COLUMN4[(y % 16) as usize][(x % 32) as usize]) as usize;
        let byte = self.mem[(nib / 2) % self.mem.len()];
        if nib & 1 == 0 { byte & 0xF } else { byte >> 4 }
    }

    /// CSM1 32-bit CLUT. The 16x16 block at `cbp` holds 256 colours; PSMT8
    /// uses all of them, PSMT4 the 16 starting at `csa * 16`.
    pub fn clut32(&self, cbp: u32, psm: u32, csa: u32) -> Vec<[u8; 4]> {
        let (start, len) = if psm == PSMT4 { ((csa & 0xF) * 16, 16) } else { (0, 256) };
        (start..start + len)
            .map(|i| {
                // CSM1 stores entries 8..15 and 16..23 of each 32 swapped.
                let j = (i & 0xE7) | ((i & 0x08) << 1) | ((i & 0x10) >> 1);
                self.read32(cbp, 1, j % 16, j / 16)
            })
            .collect()
    }
}

/// Decoded fields of a `TEX0` register.
#[derive(Clone, Copy, Debug)]
pub struct Tex0 {
    pub tbp: u32,
    pub tbw: u32,
    pub psm: u32,
    pub tw: u32,
    pub th: u32,
    pub tcc: bool,
    pub cbp: u32,
    pub cpsm: u32,
    pub csm: u32,
    pub csa: u32,
}

impl Tex0 {
    pub fn decode(v: u64) -> Self {
        let f = |shift: u32, bits: u32| ((v >> shift) & ((1 << bits) - 1)) as u32;
        Self {
            tbp: f(0, 14),
            tbw: f(14, 6),
            psm: f(20, 6),
            tw: 1 << f(26, 4),
            th: 1 << f(30, 4),
            tcc: f(34, 1) != 0,
            cbp: f(37, 14),
            cpsm: f(51, 4),
            csm: f(55, 1),
            csa: f(56, 5),
        }
    }
}

/// PS2 alpha is 0..=0x80; scale to 0..=255.
pub fn expand_alpha(a: u8) -> u8 {
    (u16::from(a) * 255 / 128).min(255) as u8
}
